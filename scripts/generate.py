"""Regenerate every generated module in the package. Never edit their output by hand.

    uv run python scripts/generate.py            # regenerate
    uv run python scripts/generate.py --check    # fail if the committed output is stale

Two generators run:

1. **The Chatwoot client** (``src/inbox_core/chatwoot/_chatwoot_api``). Chatwoot's
   own OpenAPI spec is downloaded at the pinned tag and checked against its
   SHA-256, filtered to the operations in ``codegen/chatwoot/operations.txt``
   plus ``codegen/chatwoot/overlay.json`` (operations Chatwoot serves but its
   spec omits, and corrections where the spec disagrees with Chatwoot's
   source, each citing that source), with request bodies
   reduced to JSON, and handed to ``openapi-python-client``.
2. **This service's own HTTP surface** (``src/inbox_core/chatwoot/_service_api``).
   ``src/inbox_core/chatwoot/openapi.yaml`` is the source of truth: Pydantic
   models and the FastAPI router and
   the interface it delegates to come from ``fastapi-code-generator`` with the
   template in ``codegen/service``.

The generator versions are pinned here so a regeneration is reproducible.
"""

from __future__ import annotations

import argparse
import filecmp
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CHATWOOT_TAG = "v4.19.1"
CHATWOOT_SPEC_URL = (
    "https://raw.githubusercontent.com/chatwoot/chatwoot/"
    f"{CHATWOOT_TAG}/swagger/tag_groups/application_swagger.json"
)
CHATWOOT_SPEC_SHA256 = "a06d30eb160984addc3cd85308f0b47023f2d401c7f266eedf640925756d8d3b"
OPENAPI_PYTHON_CLIENT = "openapi-python-client==0.29.1"
FASTAPI_CODE_GENERATOR = "fastapi-code-generator==0.6.0"
GENERATOR_PINS = (
    "datamodel-code-generator==0.56.1",
    "pydantic==2.14.4",
    "black==26.10.1",
    "isort==8.0.1",
)
RUFF = "ruff==0.17.6"

PACKAGE = ROOT / "src" / "inbox_core" / "chatwoot"
CLIENT_OUT = PACKAGE / "_chatwoot_api"
SERVICE_OUT = PACKAGE / "_service_api"
SERVICE_SPEC = PACKAGE / "openapi.yaml"
CODEGEN = ROOT / "codegen"
HEADER = "# Generated by scripts/generate.py. Do not edit.\n"


def _refs(node: Any, found: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/"):
            found.add(ref)
        for value in node.values():
            _refs(value, found)
    elif isinstance(node, list):
        for value in node:
            _refs(value, found)


def filter_spec(spec: dict[str, Any], keep: set[str], overlay: dict[str, Any]) -> dict[str, Any]:
    """The spec cut down to ``keep`` operations plus the overlay, with only the components used."""
    methods = {"get", "post", "put", "patch", "delete"}
    paths: dict[str, Any] = {}
    seen: set[str] = set()
    for path, item in spec["paths"].items():
        ops = {m: op for m, op in item.items() if m in methods and op.get("operationId") in keep}
        if ops:
            seen.update(op["operationId"] for op in ops.values())
            for op in ops.values():
                # inbox-core sends JSON only. Dropping the other body types
                # (multipart uploads) also avoids a generator defect in
                # 0.29.1: a two-type body is annotated with an unimported name.
                content = op.get("requestBody", {}).get("content")
                if content and "application/json" in content:
                    op["requestBody"]["content"] = {"application/json": content["application/json"]}
            shared = {k: v for k, v in item.items() if k not in methods}
            paths[path] = {**shared, **ops}
    for path, item in overlay["paths"].items():
        target = paths.setdefault(path, {})
        if "parameters" not in target and path in spec["paths"]:
            target["parameters"] = spec["paths"][path].get("parameters", [])
        for method, op in item.items():
            seen.add(op["operationId"])
            target[method] = op
    for correction in overlay.get("corrections", []):
        node = spec
        *parents, last = correction["path"]
        for key in parents:
            node = node[key]
        node[last] = correction["value"]
    missing = keep - seen
    if missing:
        raise SystemExit(f"operations not in the spec: {sorted(missing)}")

    wanted: set[str] = set()
    _refs(paths, wanted)
    components: dict[str, dict[str, Any]] = {}
    pending = list(wanted)
    while pending:
        ref = pending.pop()
        _, _, kind, name = ref.split("/", 3)
        value = spec["components"][kind][name]
        if name in components.setdefault(kind, {}):
            continue
        components[kind][name] = value
        more: set[str] = set()
        _refs(value, more)
        pending.extend(more - wanted)
        wanted |= more
    components["securitySchemes"] = spec["components"]["securitySchemes"]
    return {
        "openapi": spec["openapi"],
        "info": {**spec["info"], "title": "Chatwoot (subset used by inbox-core)"},
        "servers": spec.get("servers", []),
        "paths": paths,
        "components": components,
    }


def _download_spec() -> dict[str, Any]:
    with urllib.request.urlopen(CHATWOOT_SPEC_URL, timeout=60) as response:  # noqa: S310
        raw = response.read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != CHATWOOT_SPEC_SHA256:
        raise SystemExit(f"Chatwoot spec checksum mismatch: {digest}")
    loaded: dict[str, Any] = json.loads(raw)
    return loaded


def _run(*args: str) -> None:
    subprocess.run(args, check=True, cwd=ROOT)  # noqa: S603


def generate_client(out: Path, work: Path) -> None:
    """The typed Chatwoot client for the operations inbox-core calls."""
    keep = {
        line.split("#", 1)[0].strip()
        for line in (CODEGEN / "chatwoot" / "operations.txt").read_text().splitlines()
    } - {""}
    overlay = json.loads((CODEGEN / "chatwoot" / "overlay.json").read_text())
    subset = filter_spec(_download_spec(), keep, overlay)
    spec_path = work / "chatwoot-subset.json"
    spec_path.write_text(json.dumps(subset, indent=2, sort_keys=True))
    target = work / "client"
    _run(
        "uvx",
        "--from",
        OPENAPI_PYTHON_CLIENT,
        "openapi-python-client",
        "generate",
        "--path",
        str(spec_path),
        "--output-path",
        str(target),
        "--meta",
        "none",
        "--config",
        str(CODEGEN / "chatwoot" / "openapi-python-client.yaml"),
    )
    shutil.copy(spec_path, target / "chatwoot-subset.json")
    _run("uvx", RUFF, "format", "--quiet", "--line-length", "100", str(target))
    _replace(target, out)


def generate_service(out: Path, work: Path) -> None:
    """Models, router and interface for this service's own OpenAPI document."""
    routes = work / "routes"
    _run(
        "uvx",
        "--from",
        FASTAPI_CODE_GENERATOR,
        *(arg for pin in GENERATOR_PINS for arg in ("--with", pin)),
        "fastapi-codegen",
        "--input",
        str(SERVICE_SPEC),
        "--output",
        str(routes),
        "--template-dir",
        str(CODEGEN / "service"),
        "--python-version",
        "3.12",
        "--enum-field-as-literal",
        "all",
        "--disable-timestamp",
    )
    target = work / "service"
    target.mkdir()
    for name in ("models.py", "routes.py"):
        text = (routes / name).read_text()
        (target / name).write_text(HEADER + text)
    (target / "__init__.py").write_text(
        HEADER + '"""Generated from ``openapi.yaml``: models, router and interface."""\n'
    )
    _run("uvx", RUFF, "format", "--quiet", "--line-length", "100", str(target))
    _replace(target, out)


def _replace(source: Path, out: Path) -> None:
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(source, out)


def _same(a: Path, b: Path) -> bool:
    if not b.exists():
        return False
    compared = filecmp.dircmp(a, b, ignore=["__pycache__"])
    if compared.left_only or compared.right_only or compared.diff_files or compared.funny_files:
        return False
    return all(_same(a / sub, b / sub) for sub in compared.common_dirs)


def main() -> int:
    """Regenerate, or with ``--check`` compare against the committed output."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        outputs = {CLIENT_OUT: work / "out-client", SERVICE_OUT: work / "out-service"}
        generate_client(outputs[CLIENT_OUT], work)
        generate_service(outputs[SERVICE_OUT], work)
        if args.check:
            stale = [str(p.relative_to(ROOT)) for p, new in outputs.items() if not _same(new, p)]
            if stale:
                print(f"stale generated code: {stale}; run scripts/generate.py", file=sys.stderr)
                return 1
            return 0
        for committed, new in outputs.items():
            _replace(new, committed)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
