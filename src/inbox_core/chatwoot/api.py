"""The Chatwoot API calls the connection makes, over the generated client.

Every call goes through :mod:`inbox_core.chatwoot._chatwoot_api`, generated by
``scripts/generate.py`` from Chatwoot's own OpenAPI spec at the pinned tag.
This module only picks the operations, checks status codes and turns the
generated models into the few facts the connection reads.

Errors are :class:`ChatwootError`, which names the operation and the HTTP
status and never the response body, because a Chatwoot response can echo
message text.
"""

