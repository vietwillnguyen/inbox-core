AUTH_HEADER = "api_access_token"
MESSAGE_TYPES = {0: "incoming", 1: "outgoing", 2: "activity", 3: "template"}


class ChatwootError(RuntimeError):
    """A Chatwoot call failed. ``status`` is the HTTP status, or 0 for no response."""

    def __init__(self, operation: str, status: int) -> None:
        super().__init__(f"chatwoot {operation} failed (HTTP {status})")
        self.operation = operation
        self.status = status


@dataclass(frozen=True)
class ConversationFacts:
    """What the connection reads about one conversation."""

    id: int
    account_id: int
    inbox_id: int
    status: str
    labels: tuple[str, ...]
    contact_id: int | None


@dataclass(frozen=True)
class MessageFacts:
    """One message as Chatwoot's API reports it. ``content`` is hidden from ``repr``."""

    id: int
    conversation_id: int
    message_type: str
    private: bool
    sender_type: str
    sender_id: int | None
    content: str = field(repr=False)


@dataclass(frozen=True)
class AgentProfile:
    """Who a Chatwoot user token belongs to, and their role in each account."""

    id: int
    name: str = field(repr=False)
    roles: dict[int, str]


@dataclass(frozen=True)
class ConversationSummary:
    """A conversation in a listing: its id, contact and last activity (UTC)."""

    id: int
    contact_id: int | None
    last_activity_at: datetime


def _int(value: object) -> int | None:
    if isinstance(value, Unset) or value is None:
        return None
    if isinstance(value, bool):
        return None
    if isinstance(value, int | float):
        return int(value)
    if isinstance(value, str) and value.isdigit():
        return int(value)
    return None


def _str(value: object) -> str:
    return "" if isinstance(value, Unset) or value is None else str(value)


class ChatwootApi:
    """Chatwoot calls for one account, authenticated with one token.

    The service holds one for the agent bot (messages, notes, labels, status,
    assignment, reading conversations) and, for the retention job, one for an
    administrator (deleting conversations and contacts is admin-only).
    """

    def __init__(
        self,
        base_url: str,
        account_id: int,
        token: str,
        *,
        timeout: float = 10.0,
        transport: httpx.BaseTransport | None = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.account_id = account_id
        self._timeout = timeout
        self._transport = transport
        self._client = self._authenticated(token)

    def __repr__(self) -> str:
        return f"ChatwootApi(account_id={self.account_id})"

    def _authenticated(self, token: str) -> AuthenticatedClient:
        kwargs: dict[str, Any] = {}
        if self._transport is not None:
            kwargs["httpx_args"] = {"transport": self._transport}
        return AuthenticatedClient(
            base_url=self.base_url,
            token=token,
            prefix="",
            auth_header_name=AUTH_HEADER,
            timeout=httpx.Timeout(self._timeout),
            raise_on_unexpected_status=False,
            **kwargs,
        )

    @staticmethod
    def _check(operation: str, call: Any) -> Response[Any]:
        try:
            response: Response[Any] = call()
        except httpx.HTTPError:
            raise ChatwootError(operation, 0) from None
        except (TypeError, ValueError, KeyError):
            # The generated models refused the response's shape.
            raise ChatwootError(operation, 200) from None
        if response.status_code // 100 != 2:
            raise ChatwootError(operation, int(response.status_code))
        return response

    def _create_message(self, conversation_id: int, text: str, *, private: bool) -> str | None:
        body = ConversationMessageCreatePayload(
            content=text, message_type="outgoing", private=private
        )
        operation = "private note" if private else "send message"
        response = self._check(
            operation,
            lambda: create_a_new_message_in_a_conversation.sync_detailed(
                self.account_id, conversation_id, client=self._client, body=body
            ),
        )
        created = _int(getattr(response.parsed, "id", None))
        return None if created is None else str(created)

    def send_message(self, conversation_id: int, text: str) -> str | None:
        """Post a public reply the visitor sees. Returns Chatwoot's message id.

        The connection's transport to the public. Only
        :meth:`inbox_core.chatwoot.sink.ChatwootReplySink.send_to_public` calls
        it, which a test checks over the package source.
        """
        return self._create_message(conversation_id, text, private=False)

    def add_private_note(self, conversation_id: int, text: str) -> str | None:
        """Post a note only agents see."""
        return self._create_message(conversation_id, text, private=True)

    def open_conversation(self, conversation_id: int) -> None:
        """Set the conversation to ``open``, which puts it in agents' queues."""
        self._check(
            "open",
            lambda: toggle_status_of_a_conversation.sync_detailed(
                self.account_id,
                conversation_id,
                client=self._client,
                body=ToggleStatusOfAConversationBody(status="open"),
            ),
        )

    def assign(self, conversation_id: int, user_id: int) -> None:
        """Assign the conversation to an agent."""
        self._check(
            "assign",
            lambda: assign_a_conversation.sync_detailed(
                self.account_id,
                conversation_id,
                client=self._client,
                body=AssignAConversationBody(assignee_id=user_id),
            ),
        )

    def add_labels(self, conversation_id: int, labels: tuple[str, ...]) -> None:
        """Add labels, keeping the ones already there (Chatwoot's call replaces the set)."""
        current = self.get_conversation(conversation_id).labels
        merged = list(dict.fromkeys((*current, *labels)))
        self._check(
            "labels",
            lambda: conversation_add_labels.sync_detailed(
                self.account_id,
                conversation_id,
                client=self._client,
                body=ConversationAddLabelsBody(labels=merged),
            ),
        )

    def get_conversation(self, conversation_id: int) -> ConversationFacts:
        """One conversation's account, inbox, status, labels and contact."""
        response = self._check(
            "get conversation",
            lambda: get_details_of_a_conversation.sync_detailed(
                self.account_id, conversation_id, client=self._client
            ),
        )
        parsed = response.parsed
        if not isinstance(parsed, ConversationShow):
            raise ChatwootError("get conversation", int(response.status_code))
        inbox = _int(parsed.inbox_id)
        account = _int(parsed.account_id)
        found = _int(parsed.id)
        if inbox is None or found is None:
            raise ChatwootError("get conversation", int(response.status_code))
        contact = None
        meta = parsed.meta
        if not isinstance(meta, Unset):
            sender = getattr(meta, "sender", UNSET)
            contact = _int(getattr(sender, "id", None))
        labels = () if isinstance(parsed.labels, Unset) else tuple(parsed.labels)
        return ConversationFacts(
            id=found,
            account_id=account if account is not None else self.account_id,
            inbox_id=inbox,
            status=_str(parsed.status),
            labels=labels,
            contact_id=contact,
        )

    def find_message(self, conversation_id: int, message_id: int) -> MessageFacts | None:
        """The message with this id in the conversation, as the API reports it."""
        response = self._check(
            "list messages",
            lambda: list_all_messages.sync_detailed(
                self.account_id, conversation_id, client=self._client, after=message_id - 1
            ),
        )
        parsed = response.parsed
        if not isinstance(parsed, ListAllMessagesResponse200) or isinstance(parsed.payload, Unset):
            raise ChatwootError("list messages", int(response.status_code))
        for message in parsed.payload:
            if _int(message.id) != message_id:
                continue
            kind = message.message_type
            return MessageFacts(
                id=message_id,
                conversation_id=_int(message.conversation_id) or conversation_id,
                message_type=MESSAGE_TYPES.get(kind, "") if isinstance(kind, int) else "",
                private=bool(message.private) if not isinstance(message.private, Unset) else False,
                sender_type=_str(message.sender_type),
                sender_id=_int(message.sender_id),
                content=_str(message.content),
            )
        return None

    def profile(self, user_token: str) -> AgentProfile:
        """Who ``user_token`` belongs to, asked of Chatwoot with that token."""
        client = self._authenticated(user_token)
        response = self._check("profile", lambda: fetch_profile.sync_detailed(client=client))
        parsed = response.parsed
        found = _int(getattr(parsed, "id", None)) if isinstance(parsed, User) else None
        if not isinstance(parsed, User) or found is None:
            raise ChatwootError("profile", int(response.status_code))
        roles: dict[int, str] = {}
        if not isinstance(parsed.accounts, Unset):
            for account in parsed.accounts:
                account_id = _int(getattr(account, "id", None))
                if account_id is not None:
                    roles[account_id] = _str(getattr(account, "role", ""))
        return AgentProfile(id=found, name=_str(parsed.name), roles=roles)

    def inbox_ids(self, user_token: str) -> frozenset[int]:
        """The inboxes ``user_token``'s owner may see in this account, asked with that token."""
        client = self._authenticated(user_token)
        response = self._check(
            "inboxes", lambda: list_all_inboxes.sync_detailed(self.account_id, client=client)
        )
        parsed = response.parsed
        if not isinstance(parsed, ListAllInboxesResponse200) or isinstance(parsed.payload, Unset):
            raise ChatwootError("inboxes", int(response.status_code))
        found = (_int(inbox.id) for inbox in parsed.payload)
        return frozenset(i for i in found if i is not None)

    def list_conversations(self, page: int) -> tuple[ConversationSummary, ...]:
        """One page of every conversation in the account, any status, any assignee."""
        response = self._check(
            "list conversations",
            lambda: conversation_list.sync_detailed(
                self.account_id,
                client=self._client,
                status="all",
                assignee_type="all",
                page=page,
            ),
        )
        parsed = response.parsed
        if not isinstance(parsed, ConversationList) or isinstance(parsed.data, Unset):
            raise ChatwootError("list conversations", int(response.status_code))
        payload = parsed.data.payload
        if isinstance(payload, Unset):
            return ()
        found = []
        for item in payload:
            conversation_id = _int(item.id)
            seconds = _int(item.last_activity_at) or _int(item.created_at)
            if conversation_id is None or seconds is None:
                continue
            contact = None
            if not isinstance(item.meta, Unset):
                contact = _int(getattr(getattr(item.meta, "sender", None), "id", None))
            found.append(
                ConversationSummary(
                    conversation_id, contact, datetime.fromtimestamp(seconds, tz=UTC)
                )
            )
        return tuple(found)

    def delete_conversation(self, conversation_id: int) -> None:
        """Delete a conversation and its messages. Needs an administrator's token."""
        self._check(
            "delete conversation",
            lambda: delete_a_conversation.sync_detailed(
                self.account_id, conversation_id, client=self._client
            ),
        )

    def contact_conversation_count(self, contact_id: int) -> int:
        """How many conversations a contact still has."""
        response = self._check(
            "contact conversations",
            lambda: contact_conversations.sync_detailed(
                self.account_id, contact_id, client=self._client
            ),
        )
        parsed = response.parsed
        if not isinstance(parsed, ContactConversationsResponse):
            raise ChatwootError("contact conversations", int(response.status_code))
        return 0 if isinstance(parsed.payload, Unset) else len(parsed.payload)

    def delete_contact(self, contact_id: int) -> None:
        """Delete a contact. Needs an administrator's token."""
        self._check(
            "delete contact",
            lambda: contact_delete.sync_detailed(self.account_id, contact_id, client=self._client),
        )
